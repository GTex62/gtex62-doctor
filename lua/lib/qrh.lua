-- DCM's fixed one-line condition + action text, keyed by QRH procedure
-- title (the exact string a `PROC:` line names — docs/doctor-qrh.md).
-- fetch_doctor.sh emits `proc` plus a dynamic `detail`; the words shown on
-- screen live here, not in the provider. Every string is uppercase (the data
-- font has no lowercase glyphs) and short enough for one 448px DCM line.
--
--   cond   static condition line, or a function(detail) -> string
--   label  action line, left half  ("-LABEL......VALUE")
--   value  action line, right half (string, or function(detail) -> string)
--
-- Keep in step with the QRH: a new procedure there needs a row here (a proc
-- with no row still renders, as "SEE QRH" plus the title).
local T = {}

local function e(proc, cond, label, value)
  T[proc] = { cond = cond, label = label, value = value }
end

local function detail(prefix)
  return function(d)
    d = (d or ""):upper()
    if d == "" then return prefix end
    return prefix .. ": " .. d
  end
end

