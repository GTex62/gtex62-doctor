local M = { table = T }

-- {cond, label, value} for an entry ({proc, detail, tag, domain}); an
-- unmapped proc still yields a usable pointer at the QRH.
function M.text(entry)
  local row = T[entry.proc or ""]
  if not row then
    return {
      cond = ((entry.detail or entry.tag or ""):upper()),
      label = "SEE QRH",
      value = (entry.proc or "UNRECOGNIZED NOTE"),
    }
  end
  local cond = row.cond
  if type(cond) == "function" then cond = cond(entry.detail) end
  local value = row.value
  if type(value) == "function" then value = value(entry.detail) end
  return { cond = cond, label = row.label, value = value }
end

return M
